"""The built Web UI must render with no network at all.

frontend/ is generated by the asset build (`npm --prefix web run build`, see
CONTEXT.md) and no longer hand-edited source — these tests read the build
output, not web/. A CDN <script>/<link> that creeps back in breaks offline use
silently, so guard it here. Requires the asset build to have run first (CI
runs it before pytest; see .github/workflows/tests.yml).

Component/store-level correctness lives in web/'s Vitest suite instead — see
docs/adr/0003-bundler-managed-deps-replace-vendoring.md for why the old
hand-vendored-asset and ES-module-graph checks that used to live here no
longer apply to a bundled build.
"""

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / "frontend"
INDEX = FRONTEND / "index.html"

EXTERNAL_SRC = re.compile(
    r"""<(?:script|link)\b[^>]*\b(?:src|href)\s*=\s*["'](?P<url>[^"']+)["']""",
    re.I,
)


def _require_built_index() -> str:
    if not INDEX.is_file():
        pytest.fail(
            "frontend/index.html is missing — run `npm --prefix web run build` "
            "before this test (frontend/ is build output, not source)."
        )
    return INDEX.read_text(encoding="utf-8")


def _referenced_urls():
    return [m.group("url") for m in EXTERNAL_SRC.finditer(_require_built_index())]


def test_index_loads_no_remote_assets():
    remote = [u for u in _referenced_urls() if re.match(r"(https?:)?//", u, re.I)]
    assert remote == [], f"frontend/index.html must not load remote assets: {remote}"


def test_referenced_local_assets_exist():
    missing = [
        u
        for u in _referenced_urls()
        if not re.match(r"(https?:)?//|data:", u, re.I)
        and not (FRONTEND / u.split("?", 1)[0].lstrip("/")).exists()
    ]
    assert missing == [], f"frontend/index.html references missing files: {missing}"
